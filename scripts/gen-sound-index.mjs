// Run after gen-sounds.mjs. Metro needs literal require() paths, so this writes them out.
import fs from 'node:fs';
import path from 'node:path';

const root = path.join(import.meta.dirname, '..', 'assets', 'sounds');
const sets = fs.readdirSync(root).filter((d) => fs.statSync(path.join(root, d)).isDirectory());
const body = sets
  .map((set) => {
    const names = fs.readdirSync(path.join(root, set)).map((f) => f.replace('.wav', ''));
    return `  ${set}: {\n${names.map((n) => `    ${n}: require('../assets/sounds/${set}/${n}.wav'),`).join('\n')}\n  },`;
  })
  .join('\n');
fs.writeFileSync(path.join(import.meta.dirname, '..', 'lib', 'soundFiles.ts'), `// Generated by scripts/gen-sound-index.mjs.\nexport const SOUND_FILES = {\n${body}\n};\n`);
console.log('wrote lib/soundFiles.ts for', sets.join(', '));
